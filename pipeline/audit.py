def fetch_ceiling(path=TEXT_LOG_PATH):
    """The newest `fetched_at` in the journal, as a date ceiling for parsing.

    `parse_update` clamps to this: a `Latest update` later than the day we
    fetched the page is an upstream typo (2027 and 2029 both appear), not a
    date. Derived from the journal for the same reason `build_tree` stamps
    `__content_version__` from it -- a constant here would silently rewrite
    every genuinely-recent document.
    """
    newest = ""
    if path.exists():
        with path.open(encoding="utf-8") as handle:
            for line in handle:
                if not line.strip():
                    continue
                fetched = json.loads(line).get("fetched_at") or ""
                if fetched > newest:
                    newest = fetched
    if not newest:
        return datetime.datetime.now(datetime.timezone.utc)
    return datetime.datetime.fromisoformat(newest.replace("Z", "+00:00"))


def observed_on(rows):
    """The day a networked probe last actually asked, as `YYYY-MM-DD`.

    Every probe stamps each row it writes with `checked_at`, so the cache
    carries its own currency and nothing has to be told when it ran. The newest
    wins: a resumed or partial run leaves older rows beside newer ones, and the
    honest claim is the most recent observation, not the oldest.

    Returns `None` when the cache is empty or predates stamping -- callers
    publish the figure without a date rather than inventing one.

    Why this exists: a dead-scan count is a measurement of a moment, and
    `check_scans` runs on its own schedule -- its cache was 2.5 weeks older
    than the corpus when this was written. An undated figure hides that, so
    the stamp travels with the number it qualifies.
    """
    stamps = [r.get("checked_at") or "" for r in rows]
    newest = max((s for s in stamps if s), default="")
    return newest[:10] or None


def base_id(doc_id):
    """The site's own id for a document, with our collision suffix removed."""
    return CASE_SUFFIX_RE.sub("", doc_id)


