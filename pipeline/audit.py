def main():
    parser = argparse.ArgumentParser(
        description=__doc__.split("\n")[0],
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--update-about", action="store_true",
                        help="rewrite the AUDIT region and the data-stat "
                             "figures in docs/about.html")
    args = parser.parse_args()

    documents = load_documents()
    listings = load_listings()
    catalogue = load_catalogue()
    sizes = load_sizes()
    scans = load_scans()
    liveness = load_liveness()
    ceiling = fetch_ceiling()

    findings = {
        "missing": find_missing_documents(documents, catalogue, listings),
        "malformed": find_malformed_hrefs(catalogue),
        "missing_deva": find_missing_deva_titles(documents),
        "dates": find_unparseable_dates(documents, ceiling),
        "downloads": find_incomplete_downloads(documents),
        "dead_scans": find_dead_scans(scans, liveness),
        "unlisted": find_unlisted_documents(documents, listings),
        "suppressed": find_suppressed_listings(listings),
    }
    # The scrape date, from the journal `build_tree` stamps
    # `__content_version__` from -- so the About page and the topbar cannot
    # disagree about when the corpus was taken.
    stats = intro_stats(documents, listings, catalogue, sizes, scans,
                        liveness, findings, ceiling.date().isoformat())

    print_report(findings, stats)

    if args.update_about:
        update_about_html(render_audit_html(findings))
        print(f"\nwrote the audit region of {ABOUT_HTML_PATH}")
        update_about_region("TOPIC_FOLDERS",
                            render_topic_folders(documents, listings))
        print("wrote the folders-per-topic table")
        tagged = update_intro_stats(stats)
        print(f"refreshed {tagged} figures in the same file")


if __name__ == "__main__":
    main()
