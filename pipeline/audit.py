# Lifted from the e-bharatisampat sibling, which lifted them from wikisource.
# Kept identical on purpose: the three pages should look like one project.


def _esc(s):
    return html.escape(str(s))


def _sa(s):
    """Devanagari gets the site's own font treatment, same as hand-written
    About prose does with `<span class="sa-cap">` -- which
    `docs/translit-static.js` re-renders into the reader's chosen scheme.

    **Only for actual Devanagari.** `translit-static.js` converts on a
    Devanagari code-point run, so wrapping an ITRANS slug like `vishhnu` or
    `z_misc_general` in this class converts nothing and merely styles an
    identifier as if it were Sanskrit prose. Those want `<code>`, which is what
    the hand-written prose around them uses. Unused by the current renderers
    for exactly that reason, and kept for the first finding that does name a
    Devanagari title.
    """
    return f'<span class="sa-cap">{_esc(s)}</span>'


def _doc_link(doc_id, label=None):
    """Link to the document's own page, built as `docs/app.js` does.

    The `~<hash>` suffix is ours, not the site's, so it comes off before the
    URL is built -- linking to it would 404.
    """
    href = f"{SITE_ROOT}/{base_id(doc_id)}.html"
    return (f'<a href="{html.escape(href)}" target="_blank" rel="noopener">'
            f"{_esc(label or doc_id)}</a>")


def _findings_list(items):
    """`items` are already-escaped HTML fragments -- this only wraps them in
    <li>/<ul> and must not re-escape. Indented past its own <summary>'s
    triangle, which the global `.content ul` reset does not clear."""
    lis = "\n".join(f"            <li>{item}</li>" for item in items)
    return f'          <ul style="margin-left: 1.6em;">\n{lis}\n          </ul>'


def _summary_text(description, label):
    """The summary's own content, wrapped in one span.

    `.audit-summary` is `display: flex` (for the triangle), which makes every
    child a flex item -- and flex DISCARDS the whitespace between items. A
    description ending in an element, as ours do when a name is wrapped in
    `<span class="sa-cap">`, would otherwise render as "shiva(34 documents)"
    with the space silently eaten. One wrapper span makes the whole label a
    single flex item, and the space inside it survives.
    """
    return f"<span>{description} ({label})</span>"


def _bullet(description, count, inner_html, unit=None):
    """One finding row. `unit` spells out what the number counts, for cases
    where a bare figure would mislead. A zero-count check still renders, as
    "none found" with an invisible spacer where the triangle would be --
    silence and success must not look the same."""
    if count == 0:
        # Same one-flex-item wrapper as _summary_text, for the same reason.
        return (f'          <li class="audit-item"><div class="audit-summary '
                f'audit-summary-empty"><span>{description}: none found</span></div></li>')
    label = unit if unit is not None else str(count)
    return (
        f'          <li class="audit-item"><details>\n'
        f'            <summary class="audit-summary">{_summary_text(description, label)}</summary>\n'
        f"{inner_html}\n"
        f"          </details></li>"
    )


def _sub_bullet(description, count, inner_html, unit=None):
    """Same construction one level in, for grouping a flat list into
    collapsible sub-groups. Reuses .audit-item/.audit-summary so the triangle
    and spacing match the top-level findings exactly."""
    label = unit if unit is not None else str(count)
    return (
        f'<li class="audit-item"><details>\n'
        f'<summary class="audit-summary">{_summary_text(description, label)}</summary>\n'
        f"{inner_html}\n"
        f"</details></li>"
    )


def _group_ul(items):
    """A nested list of audit bullets -- same wrapper both siblings use
    between a <summary> and its child findings."""
    return ('          <ul style="margin-left: 1.6em; list-style: none; padding-left: 0;">\n'
            + "\n".join(f"            {item}" for item in items)
            + "\n          </ul>")


def _preamble(text_html):
    """One line between a finding's summary and its items.

    The only prose a finding carries. It says what the reader is looking at and
    must stay a single sentence; anything longer is the restated context the
    findings deliberately drop.
    """
    return f'          <p style="margin-left: 1.6em;">{text_html}</p>'


MONTHS = ("January", "February", "March", "April", "May", "June", "July",
          "August", "September", "October", "November", "December")


def _month_name(iso):
    """`2025-02-16` -> `February 2025`. Day precision is dropped: the date
    bounds a diff, and a reader does not need the day the snapshot was taken."""
    try:
        year, month = iso.split("-")[:2]
        return f"{MONTHS[int(month) - 1]} {year}"
    except (ValueError, IndexError):
        return iso


def _as_of(checked_at):
    """A trailing ` Checked <date>.` for a finding a probe measured.

    Empty when the cache carries no stamp, so an unstamped older cache
    publishes its finding undated rather than blank or wrongly dated. The date
    is the PROBE's, never the audit run's -- see `observed_on`.
    """
    if not checked_at:
        return ""
    return f" Checked {_month_name(checked_at)}."


def _capped(items):
    """Trim a long example list, saying so rather than truncating silently."""
    if len(items) <= MAX_EXAMPLES:
        return items
    return items[:MAX_EXAMPLES] + [
        f"<em>… and {len(items) - MAX_EXAMPLES:,} more</em>"]


