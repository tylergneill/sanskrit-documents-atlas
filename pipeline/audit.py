def render_topic_folders(documents, listings):
    """The "Which folders each topic draws on" table.

    Was hand-written HTML sitting OUTSIDE the AUDIT region, and had drifted:
    17 of its 85 rows overstated their doc count, every one of them from
    before the 25 documents the site 404s stopped being held. Exactly the
    failure the data-stat contract exists to prevent, one level up -- a whole
    table rather than a single figure -- so it is generated here now.

    Counts only documents actually held, the same `in held` discipline
    `build_tree.build_by_listing` applies, so a row can never claim more
    documents than the tree ships.
    """
    held = {d["doc_id"]: d["location"] for d in documents}
    rows = []
    for row in listings:
        docs = [d for d in row.get("doc_ids") or [] if d in held]
        if not docs:
            continue
        folders = collections.Counter(held[d] for d in docs)
        rows.append((row["slug"], len(docs), folders))
    rows.sort(key=lambda r: (-r[1], r[0]))

    cell = 'padding:2px 12px 2px 0;'
    num = 'padding:2px 12px 2px 0; text-align:right;'
    body = []
    for slug, count, folders in rows:
        top = folders.most_common(3)
        # `doc_` stripped: every folder carries it, so it is noise in a column
        # of folder names, and the prose around this table already writes them
        # bare (`devii`, `deities_misc`).
        parts = [f"<code>{_esc(name.removeprefix('doc_'))}</code>"
                 f"&nbsp;{round(n / count * 100)}%"
                 for name, n in top]
        if len(folders) > len(top):
            parts.append(f'<span style="opacity:.6;">+{len(folders) - len(top)} more</span>')
        body.append(
            f'                <tr><td style="{cell}"><code>{_esc(slug)}</code></td>'
            f'<td style="{num}">{count:,}</td>'
            f'<td style="{num}">{len(folders)}</td>'
            f'<td style="padding:2px 0;">{"; ".join(parts)}</td></tr>')

    head = (
        '                <tr style="border-bottom:1px solid var(--border);">\n'
        f'                  <th style="{cell} text-align:left;">topic</th>\n'
        f'                  <th style="{num}">docs</th>\n'
        f'                  <th style="{num}">folders</th>\n'
        '                  <th style="padding:2px 0; text-align:left;">drawn from</th>\n'
        "                </tr>")
    table = (
        '          <div style="overflow-x:auto;">\n'
        '            <table style="border-collapse:collapse; font-size:13px; margin:0 0 4px;">\n'
        f"              <thead>\n{head}\n              </thead>\n"
        "              <tbody>\n" + "\n".join(body) + "\n              </tbody>\n"
        "            </table>\n"
        "          </div>")
    return (
        '        <ul style="list-style: none; padding-left: 0; margin: 0;">\n'
        '          <li class="audit-item"><details>\n'
        '            <summary class="audit-summary"><span>Which folders each '
        "topic draws on</span></summary>\n"
        f"{table}\n"
        "          </details></li>\n"
        "        </ul>")


def render_audit_html(findings):
    """The published region: upstream findings only.

    `OURS_CHECKS` is deliberately not rendered. The audit's subject is the
    source collection -- what a reader could go fix on sanskritdocuments.org --
    and a section reporting our own defects (or, once fixed, reporting none)
    is noise against that purpose. Those checks still run and still print to
    the console, where the person who can act on them will see them.
    """
    upstream = [render(findings[key]) for key, render in UPSTREAM_CHECKS]
    return (
        '        <h3 id="opportunities-for-correction">Opportunities for Correction</h3>\n'
        "        <p>\n"
        "          The Atlas codebase also includes an audit pipeline for\n"
        "          detecting and concisely indicating problems that should be fixed on\n"
        "          sanskritdocuments.org. Every figure below is re-derived by the run\n"
        "          that publishes it.\n"
        "        </p>\n"
        '        <ul style="list-style: none; padding-left: 0;">\n'
        + "\n".join(upstream)
        + "\n        </ul>"
    )


# --- writing back -----------------------------------------------------------


def update_about_region(name, new_html, path=ABOUT_HTML_PATH):
    """Replace the block between one pair of `<!-- NAME:START/END -->` markers.

    A targeted string splice, not an HTML parse, so the rest of the file and
    the markers themselves are untouched. `name` selects the region: AUDIT for
    the Data Quality findings, TOPIC_FOLDERS for the folders-per-topic table.
    """
    start_marker = MARKERS[name][0]
    end_marker = MARKERS[name][1]
    text = path.read_text(encoding="utf-8")
    try:
        start = text.index(start_marker) + len(start_marker)
        end = text.index(end_marker)
    except ValueError as err:
        raise SystemExit(
            f"{path} has no {name}:START/{name}:END markers -- add them around "
            f"the region before running with --update-about"
        ) from err
    path.write_text(text[:start] + "\n" + new_html + "\n        " + text[end:],
                    encoding="utf-8")


def update_about_html(new_html, path=ABOUT_HTML_PATH):
    """Back-compat wrapper for the AUDIT region."""
    update_about_region("AUDIT", new_html, path)


def _fmt(value):
    """Integers get thousands separators; rates keep one decimal.

    Percentages and ratios are floats and must not be comma-grouped, rounded
    to int, or stripped of a trailing zero -- a coverage rate of 100.0% would
    publish as "100" and read as a count, and a ratio of 1.87 would round to
    "2". A stat that genuinely wants a whole number says so by being an int at
    the computation site, rather than by loosening this.
    """
    if isinstance(value, str):
        return value  # already formatted at the computation site
    if isinstance(value, int):
        return f"{value:,}"
    return f"{value:.3f}" if abs(value) < 1 else f"{value:,.1f}"


def update_intro_stats(stats, path=ABOUT_HTML_PATH):
    """Rewrite each `data-stat="..."` figure in the hand-written prose.

    Per-element substitution rather than a marker region: these numbers sit
    inside authored sentences, so there is no contiguous block to splice. The
    tag is the contract -- prose around it can be rewritten freely, and only
    the digits between the tagged element's own `>`/`<` are replaced.

    A tag naming a stat we do not compute, or a stat with no tag, is an error
    rather than a skip: silently leaving a stale figure on the page is exactly
    the failure this replaces.
    """
    text = path.read_text(encoding="utf-8")
    seen = set()

    def sub(match):
        key = match.group("key")
        if key not in stats:
            if key in EXTERNAL_STATS or key in MIRROR_STATS:
                # Offline run, or no local mirror -- leave the measured value.
                return match.group(0)
            raise SystemExit(
                f'{path} tags data-stat="{key}", which the audit does not compute'
            )
        seen.add(key)
        return f"{match.group('open')}{_fmt(stats[key])}{match.group('close')}"

    pattern = re.compile(
        r'(?P<open><(?P<tag>span|text)\b[^>]*\bdata-stat="(?P<key>[^"]+)"[^>]*>)'
        r"[^<]*"
        r"(?P<close></(?P=tag)>)"
    )
    updated = pattern.sub(sub, text)

    # Write BEFORE validating the reverse direction. The check below is about
    # the *next* edit -- a figure that has drifted out of the prose -- while
    # `updated` already holds correct values for every tag that is present.
    # Raising first discarded the whole substitution, so from the commit that
    # introduced this stage until 2026-08-24 no data-stat figure was ever
    # written and every number on the page was still the hand-typed one.
    path.write_text(updated, encoding="utf-8")

    # EXTERNAL_STATS are exempt in BOTH directions. `sub` already leaves such a
    # tag alone when an offline run did not measure it; the same figures must
    # not be *required* to have a tag, or the page can never satisfy both rules
    # at once.
    missing = sorted(set(stats) - seen - EXTERNAL_STATS)
    if missing:
        raise SystemExit(
            f"{path} has no data-stat tag for: {', '.join(missing)} -- "
            f"tag the figure in the prose or drop it from intro_stats()"
        )
    return len(seen)  # distinct stats published, not tag sites


# --- report -----------------------------------------------------------------


def print_report(findings, stats):
    print(f"audit of {stats['total']:,} documents "
          f"({datetime.date.today().isoformat()})\n")
    rows = [
        ("listed but not served", findings["missing"]["count"]),
        ("malformed catalogue hrefs", findings["malformed"]["count"]),
        ("no Devanagari title", findings["missing_deva"]["count"]),
        ("no usable date", findings["dates"]["count"]),
        ("incomplete download set", findings["downloads"]["count"]),
        ("dead scanned sources", findings["dead_scans"]["count"]),
        ("duplicate topic pages", findings["suppressed"]["count"]),
    ]
    print("  upstream, fixable on sanskritdocuments.org")
    for label, count in rows:
        print(f"    {count:>6,}  {label}")
    unlisted = findings["unlisted"]
    print("\n  ours")
    # `explained` is vacuously true at zero, so guard on the count too --
    # otherwise a clean run annotates nothing as "all case-collision pairs".
    note = (" (all case-collision pairs)"
            if unlisted["count"] and unlisted["explained"] else "")
    print(f"    {unlisted['count']:>6,}  dropped by the topics axis{note}")
    dead = findings["dead_scans"]
    if not dead.get("unchecked") and dead["count"]:
        print(f"\n  dead scans strand {dead['links']:,} links across "
              f"{dead['docs']:,} documents")


