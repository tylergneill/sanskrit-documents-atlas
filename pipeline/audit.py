def render_missing(finding):
    groups = []
    by_loc = collections.defaultdict(list)
    for doc_id in finding["ids"]:
        by_loc[doc_id.split("/")[0]].append(doc_id)
    for location, ids in sorted(by_loc.items(), key=lambda kv: -len(kv[1])):
        entries = []
        for doc_id in ids:
            slugs = finding.get("on_listing", {}).get(doc_id) or []
            also = ""
            if slugs:
                pages = ", ".join(f"<code>{_esc(s)}</code>" for s in slugs)
                also = f" — also on {pages}"
            entries.append(_doc_link(doc_id, doc_id.split("/", 1)[1]) + also)
        groups.append(_sub_bullet(f"<code>{_esc(location)}</code>",
                                  len(ids), _findings_list(entries)))
    both = finding.get("on_both", 0)
    shared = (f" All {both} are linked from a topic page "
              f"(<code>/sanskrit/&lt;slug&gt;/</code>) as well as from their "
              f"folder page, so both of the site's indexes carry the same "
              f"dead entries." if both == finding["count"] and both else "")
    inner = (_preamble("The site's own indexes link each of these, but "
                       "requesting it returns 404." + shared)
             + "\n" + _group_ul(groups))
    return _bullet("Documents listed but no longer served",
                   finding["count"], inner,
                   unit=f"{finding['count']} documents")


def render_malformed(finding):
    entries = [f"<code>{_esc(d)}</code>" for d in finding["ids"]]
    inner = (_preamble("Bad hrefs on the site's own topic pages — a literal "
                       "space in a path, and a <code>.inf</code> target that "
                       "is not a document.")
             + "\n" + _findings_list(entries))
    return _bullet("Malformed links in the catalogue", finding["count"], inner,
                   unit=f"{finding['count']} entries")


def render_missing_deva(finding):
    entries = [_doc_link(d, d.split("/", 1)[1]) for d in finding["ids"]]
    inner = (_preamble("Only <code>title_deva</code> can be transliterated — "
                       "the English label and the filename stem are both ad-hoc "
                       "romanization — so a document without one cannot render "
                       "in a reader's chosen script. These pages carry no "
                       "Devanāgarī title; the atlas shows an approximation "
                       "rebuilt from the filename, which is lossy where the "
                       "site's spelling cannot express a sound.")
             + "\n" + _findings_list(_capped(entries)))
    return _bullet("Documents without a given Devanāgarī title",
                   finding["count"], inner,
                   unit=f"{finding['count']} documents")


def render_dates(finding):
    groups = []
    if finding["corrupt"]:
        entries = [f"{_doc_link(d, d.split('/', 1)[1])} — <code>{_esc(raw)}</code>"
                   for d, raw in finding["corrupt"]]
        groups.append(_sub_bullet("corrupt", len(finding["corrupt"]),
                                  _findings_list(entries)))
    if finding["blank"]:
        entries = [_doc_link(d, d.split("/", 1)[1]) for d, _ in finding["blank"]]
        groups.append(_sub_bullet("blank", len(finding["blank"]),
                                  _findings_list(entries)))
    inner = (_preamble("<em>Latest update</em> is the only date the corpus "
                       "carries about itself, and on these it is blank or "
                       "unreadable.")
             + "\n" + _group_ul(groups))
    return _bullet("Documents with no usable date", finding["count"], inner,
                   unit=f"{finding['count']} documents")


def render_downloads(finding):
    entries = [f"{_doc_link(d, d.split('/', 1)[1])} — {n} of 7"
               for d, n in finding["items"]]
    # Two kinds in one finding, and the wording has to cover both: a real
    # document missing some PDFs, and a page with nothing to generate them
    # from. The 0-of-7 pair are metadata-only shells -- no `div#article`, no
    # Devanagari -- so "short of the set" would describe them as documents.
    inner = (_preamble("Nearly every document is published as its ITX source "
                       "plus five generated PDFs. The one at 3 of 7 is short "
                       "of the set; the two at 0 of 7 are metadata-only pages "
                       "with no text to generate anything from.")
             + "\n" + _findings_list(entries))
    return _bullet("Documents missing download formats", finding["count"], inner,
                   unit=f"{finding['count']} documents")


def render_dead_scans(finding):
    if finding.get("unchecked"):
        return ('          <li class="audit-item"><div class="audit-summary '
                'audit-summary-empty"><span>Dead scanned-source links: '
                'not checked (run <code>make check-scans</code>)</span></div></li>')
    groups = []
    by_kind = collections.defaultdict(list)
    for stem in finding["stems"]:
        by_kind[finding["detail"][stem]["kind"]].append(stem)
    for kind, stems in sorted(by_kind.items(), key=lambda kv: -len(kv[1])):
        entries = []
        for stem in stems:
            row = finding["detail"][stem]
            status = row.get("status") or row.get("error") or "?"
            entries.append(
                f'<a href="{html.escape(row["url"])}" target="_blank" '
                f'rel="noopener">{_esc(stem)}</a> — <code>{_esc(status)}</code>')
        groups.append(_sub_bullet(_esc(kind), len(stems),
                                  _findings_list(_capped(entries))))
    inner = (_preamble(
        f"Counted by book, not by link: these {finding['count']:,} dead sources "
        f"strand {finding['links']:,} links across {finding['docs']:,} documents, "
        f"because the dead ones are disproportionately heavily-cited anthologies."
        + _as_of(finding.get("checked_at")))
        + "\n" + _group_ul(groups))
    return _bullet("Scanned sources that no longer resolve", finding["count"],
                   inner, unit=f"{finding['count']} books")


def render_suppressed(finding):
    entries = []
    for item in finding["items"]:
        url = f"{SITE_ROOT}/sanskrit/{item['alias']}/"
        kept = f"{SITE_ROOT}/sanskrit/{item['kept']}/"
        entries.append(
            f'<a href="{html.escape(url)}" target="_blank" rel="noopener">'
            f"<code>{_esc(item['alias'])}</code></a> — {_esc(item['note'])} "
            f'<a href="{html.escape(kept)}" target="_blank" rel="noopener">'
            f"<code>{_esc(item['kept'])}</code></a>")
    inner = (_preamble(
        "The site publishes these as separate topic pages, but each says "
        "nothing its counterpart does not. The tree shows the one named "
        "second; these names reach it too.")
        + "\n" + _findings_list(entries))
    return _bullet("Topic pages the site duplicates", finding["count"],
                   inner, unit=f"{finding['count']} pages")


def render_unlisted(finding):
    groups = []
    for base, ids in finding["pairs"].items():
        entries = [_doc_link(d, d.split("/", 1)[1]) for d in ids]
        groups.append(_sub_bullet(_esc(base.split("/", 1)[-1]), len(ids),
                                  _findings_list(entries)))
    inner = (_preamble(
        "Each is half of a pair whose ids differ only by letter case, which "
        "macOS and Windows collapse into one file. Both pages were fetched and "
        "both are in the tree — but the id reaching the tree is not the id the "
        "site uses, so the join against the topic pages misses. This is ours "
        "to fix, in whatever mints the id.")
        + "\n" + _group_ul(groups))
    return _bullet("Documents the topics axis drops", finding["count"],
                   inner, unit=f"{finding['count']} documents")


