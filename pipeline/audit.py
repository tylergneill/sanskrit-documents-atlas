# The rows of the Metadata Fields table, in the order they are published --
# richest first, which is also the order that makes the table's point: the
# site fills in what identifies a text and thins out toward what describes it.
#
# **The rule, stated so it stops being implicit.** A row here is an
# `<pre class="inf">` key that (a) the site fills in per document -- it varies
# across the corpus and says something about *this* text -- and (b) the parser
# actually extracts, so the number is measurable rather than guessed.
#
# What that rule excludes, and why each is a deliberate absence rather than an
# oversight -- the distinction this list failed to make until 2026-09-07, when
# nine extracted-nowhere fields were found sitting silently outside it:
#
#   ours, not the site's   `source_url` and `itxtitle` are derived rather than
#                          catalogued, and `sublocation` is upstream noise that
#                          merely repeats the location (see the 2026-08-24
#                          entry in `notes/scratch/todo.md`). Publishing
#                          coverage for these would describe our parser.
#   boilerplate            `Site access` is one site URL on all 9,756 documents
#                          (two spellings, http and https) and `Send
#                          corrections to` is one contact address on 9,750
#                          (thirteen spellings of the same mailbox). Both are
#                          the site's footer, printed per page; neither is a
#                          fact about the text, so a 100% row for either would
#                          measure the template.
#   the same field twice   `File name`, `Text title`, `engtitle` and `Location`
#                          restate `stem`, `title` and `location`, which the
#                          record already carries from elsewhere on the page.
#
# Order is richest first, which is also the order that makes the table's point:
# the site fills in what identifies a text and thins out toward what describes
# it. Hand-sorted -- re-check it when coverage moves.
COVERAGE_FIELDS = [
    "title", "language", "categories", "title_deva", "latest_update",
    "subject", "proofread_by", "indexextra", "description",
    "transliterated_by", "author", "subdeity", "acknowledge_permission",
    "texttype", "source", "translated_by", "subcategory",
]

# field -> the record flag meaning "this value was synthesized, not read off
# the page". A flagged value is not coverage: the table reports what the source
# fills in, and counting our own fallback republishes the pipeline as the site.
DERIVED_FROM = {"title_deva": "title_deva_reconstructed"}


def field_coverage(documents):
    """`cov_<field>` / `covpct_<field>` for every field the page quotes.

    Generated from one list rather than written out, so tagging a new field in
    the prose is a one-line change here.

    "Covered" is non-empty after stripping, and `categories` is a list rather
    than a string -- a bare `.strip()` raises on it, so emptiness is tested
    per-type instead.

    **A reconstructed value is not coverage.** This table measures what
    sanskritdocuments.org fills in, so a value the pipeline rebuilds must not
    count toward it. `title_deva` is the case: 76 documents carry no Devanagari
    title, and `parse_snapshot.reconstruct_deva` approximates one from the
    `itxtitle` field, flagging it `title_deva_reconstructed`. That is not the
    same kind of value -- the source romanization is not a real scheme, so the
    rebuild is lossy where every banner-read title is exact.

    Counting them published `title_deva` at 100.0% from 2026-08-28 (when the
    fallback landed) to 2026-09-07: 9,680 the day before, with nothing about the
    source changed. DERIVED_FROM names the flag that disqualifies a value; add
    an entry whenever a new field gains a fallback.
    """
    stats = {}
    total = len(documents)
    # The row count itself, so the prose above the table cannot quote a
    # different number than the table shows. Counted here rather than typed
    # because adding to COVERAGE_FIELDS must move both together.
    stats["metadata_fields"] = len(COVERAGE_FIELDS)
    for field in COVERAGE_FIELDS:
        derived_flag = DERIVED_FROM.get(field)
        n = 0
        for doc in documents:
            if derived_flag and doc.get(derived_flag):
                continue
            value = doc.get(field)
            if isinstance(value, list):
                n += bool(value)
            else:
                n += bool((value or "").strip())
        stats[f"cov_{field}"] = n
        stats[f"covpct_{field}"] = round(n / total * 100, 1)
    return stats


# Punctuation, addresses and case vary between the two credit lines for the
# same person ("Ruma Dewan" vs "ruma dewan ruma at example.com"), so equality
# is tested on letters alone, with any address stripped first. Containment
# counts as a match because one line is often the other plus a second name.
_CREDIT_ADDRESS_RE = re.compile(r"\S+@\S+|\S+\s+at\s+\S+\s+dot\s+\S+")
_CREDIT_KEEP_RE = re.compile(r"[^a-z ]")


def _credit_key(value):
    value = _CREDIT_ADDRESS_RE.sub(" ", (value or "").lower())
    return " ".join(_CREDIT_KEEP_RE.sub(" ", value).split())


def credit_stats(documents):
    """Who is named for getting a text into the corpus, and how often.

    **`proofread_by` is the input credit, not a checking step**, and the
    figures here are what says so: `credit_sole` documents name that person and
    nobody else. Someone typed each of those, so on a volunteer archive whose
    credit line exists to thank the person who did the work, that person is the
    one named. `transliterated_by` is a second hand where a second hand was
    involved -- it appears on fewer than half the corpus, and agrees with the
    input credit `credit_same_pct` of the time it appears at all.

    Named on the About page rather than left as a reading of the field labels,
    because the labels invite the opposite reading and nothing else on the page
    corrects it.
    """
    sole = both = same = 0
    for doc in documents:
        proofreader = (doc.get("proofread_by") or "").strip()
        translit = (doc.get("transliterated_by") or "").strip()
        if proofreader and not translit:
            sole += 1
        elif proofreader and translit:
            both += 1
            a, b = _credit_key(proofreader), _credit_key(translit)
            if a and b and (a == b or a in b or b in a):
                same += 1
    return {
        "credit_sole": sole,
        "credit_both": both,
        "credit_same_pct": round(same / both * 100, 1) if both else 0.0,
    }


def _and_list(parts):
    """"a", "a and b", "a, b, and c" -- for stats whose value is a name list.

    A name list is a `str` stat, so it reaches the page through `_fmt`
    untouched; the joining has to happen here, at the computation site, like
    every other preformatted figure.
    """
    parts = list(parts)
    if len(parts) <= 2:
        return " and ".join(parts)
    return f"{', '.join(parts[:-1])}, and {parts[-1]}"


def intro_stats(documents, listings, catalogue, sizes, scans, liveness,
                findings, corpus_date_str):
    """Every figure the hand-written prose quotes, re-derived.

    Returns a flat `{key: int|float}`. The type IS the format contract --
    `_fmt` gives an int thousands separators and a float one decimal -- so a
    figure that wants a whole number says so by being `round(x)` here, never by
    loosening `_fmt`.
    """
    total = len(documents)
    stats = {"total": total, "catalogue": len(catalogue)}

    # Axis 1: the canonical folder (the site's `Location`), one per document.
    locations = collections.Counter(d["location"] for d in documents)
    stats["folders"] = len(locations)
    stats["folders_misc"] = sum(1 for loc in locations if "z_misc" in loc)
    stats["folders_nonmisc"] = stats["folders"] - stats["folders_misc"]

    # Axis 2: the site's own topic pages, freely overlapping.
    placements = collections.Counter()
    for row in listings:
        for doc_id in row.get("doc_ids") or []:
            placements[doc_id] += 1
    listed = [placements[d["doc_id"]] for d in documents if d["doc_id"] in placements]
    # The pages we SHOW. The site publishes two more that duplicate others --
    # `find_suppressed_listings` names them, and the About page says so where it
    # quotes this number.
    stats["topic_pages"] = len(listings)
    stats["topic_pages_suppressed"] = findings["suppressed"]["count"]
    stats["topic_pages_published"] = (
        len(listings) + findings["suppressed"]["count"])
    # ...and NAME them. Two prose stats rather than one tag per slug, so the
    # contract holds however many aliases the site grows: each is a rendered
    # phrase, already formatted (`_fmt` passes a str through), and the pair is
    # ordered the same way so "giitaa and vishhnu" lines up with "gita and
    # vishnu" read in the same order.
    suppressed = findings["suppressed"]["items"]
    stats["topic_pages_suppressed_names"] = _and_list(
        f"/sanskrit/{i['alias']}/" for i in suppressed)
    stats["topic_pages_suppressed_kept"] = _and_list(
        f"/sanskrit/{i['kept']}/" for i in suppressed)
    # No `on_topics`/`off_topics` here on purpose. The axes reach the same
    # 9,756 documents, so both figures are constants -- the corpus total and
    # zero -- and publishing them invited the page to narrate an atlas-side
    # defect that no longer exists. `find_unlisted_documents` still runs; it
    # just reports to the console rather than to readers.
    # Two decimals, preformatted: `_fmt` gives floats one, and "2.3 pages"
    # loses the precision the axis argument rests on.
    stats["mean_topics"] = f"{sum(listed) / len(listed):.2f}"
    stats["max_topics"] = max(listed)

    # How wide a single topic reaches across the OTHER axis -- the folder
    # spread of each topic's members. The inverse of `max_topics`, which counts
    # topics per document; this counts folders per topic, and is what the About
    # page means by "a topic draws on as many folders as needed, from one to
    # sixteen". Restricted to documents actually held, the same `in held`
    # discipline `build_tree.build_by_listing` applies, so the page cannot
    # quote a wider spread than the tree it ships beside.
    held_location = {d["doc_id"]: d["location"] for d in documents}
    spreads = []
    for row in listings:
        folders = {held_location[doc_id]
                   for doc_id in row.get("doc_ids") or []
                   if doc_id in held_location}
        if folders:
            spreads.append(len(folders))
    # Only the max is published: the floor is 1 by construction (a topic with
    # no held members is skipped), so tagging it would generate a constant.
    stats["max_topic_folders"] = max(spreads)

    # The Category bag.
    tags = collections.Counter()
    for doc in documents:
        for tag in doc.get("categories") or []:
            tags[tag] += 1
    # Every slug the SITE publishes, suppressed ones included -- the suppression
    # of `/sanskrit/vishhnu/` and `/sanskrit/giitaa/` is our display decision
    # about topic pages, not a fact about the site's vocabulary.
    slugs = {row["slug"] for row in listings}
    for row in listings:
        slugs.update(row.get("aliases") or [])
    # Pre-fold spelling count, from the sidecar: `documents` is already
    # normalized, so this cannot be counted here.
    stats["raw_spellings"] = load_inventory_meta()["raw_category_spellings"]
    stats["categories_unique"] = len(tags)
    stats["categories_matching_a_topic"] = sum(1 for tag in tags if tag in slugs)
    stats["categories_not_matching_a_topic"] = (
        stats["categories_unique"] - stats["categories_matching_a_topic"])
    stats["mean_categories"] = (
        f"{sum(len(d.get('categories') or []) for d in documents) / total:.2f}")
    # Name and count together: quoting "tagged N times" without saying which tag
    # invites the two from drifting apart on the page.
    top_unmatched = max(
        ((n, tag) for tag, n in tags.items() if tag not in slugs),
        default=(0, ""))
    stats["category_not_matching_a_topic_top_count"] = top_unmatched[0]
    stats["category_not_matching_a_topic_top_name"] = top_unmatched[1]

    # The 2020 mirror's corrective, re-derived rather than read back from
    # `changelog.json`: presence in a dated dump proves a document existed by
    # then whatever its `Latest update` claims, and `Latest update` only ever
    # errs late. Must mirror `build_changelog` exactly -- same
    # `load_attestations`, same `parse_update`, same ceiling -- since the page
    # and the chart publish the same correction.
    #
    # The mirror is local-only and not every machine has it, exactly as the
    # Makefile assumes when it passes `--attest` conditionally. But the stat
    # contract needs the key present either way, so an absent mirror keeps the
    # figure already in the page rather than publishing a wrong one: the
    # correction is a fact about the mirror, and a machine that cannot see it
    # has nothing to say about it.
    ceiling = corpus_date(TEXT_LOG_PATH)
    # Both corpora, exactly as the Makefile's `ATTEST` passes them -- a figure
    # here derived from fewer dumps than the chart uses would disagree with the
    # chart it sits beside. Each is included only if its inventory exists, so a
    # machine with neither still runs and keeps whatever the page publishes.
    sources = [(DUMP_2020_INVENTORY_PATH, DUMP_2020_DATE),
               (INVENTORY_PATH, SNAPSHOT_DATE)]
    attested = load_attestations(
        [f"{path}:{date}" for path, date in sources if path.exists()])
    pulled_back = pulled_pre = 0
    cutoff = datetime.datetime.fromisoformat(DUMP_2020_DATE).replace(
        tzinfo=datetime.timezone.utc)
    for doc in documents:
        when = parse_update(doc.get("latest_update") or "", ceiling)
        floor = attested.get(doc["doc_id"])
        # A floor only ever lowers a date -- the bucket is a `min` over the
        # stamp and every attestation -- so adding a corpus can pull a document
        # earlier or leave it alone, never push it later. Checked: zero
        # documents bucket later with both dumps than with the mirror alone.
        if floor is not None and when is not None and floor < when:
            pulled_back += 1
            if floor <= cutoff:
                pulled_pre += 1
    # Documents with no usable date of their own that an earlier corpus can
    # still place. Distinct from `dates_unusable`, which counts broken fields
    # whether or not anything can date them -- the two are equal only while
    # every unusable document happens to sit in one of the dumps.
    stats["bad_dates_rescued"] = sum(
        1 for doc in documents
        if parse_update(doc.get("latest_update") or "", ceiling) is None
        and attested.get(doc["doc_id"]) is not None)
    if attested:
        stats["attested_pulled_back"] = pulled_back
        # Where they land. The mirror is the only corpus that can carry a
        # document across the 2020 line, so this split is also which dump did
        # the work -- and it is why the pre-2020 share is nearly all of it.
        stats["attested_pulled_pre2020_pct"] = round(
            pulled_pre / pulled_back * 100) if pulled_back else 0
        stats["attested_pulled_mid_pct"] = (
            100 - stats["attested_pulled_pre2020_pct"] if pulled_back else 0)

    # Cataloguing.
    stats["languages"] = len(
        {(d.get("language") or "").strip() for d in documents
         if (d.get("language") or "").strip()})
    stats["sanskrit"] = sum(
        1 for d in documents if (d.get("language") or "").strip() == "Sanskrit")
    stats["sanskrit_pct"] = round(stats["sanskrit"] / total * 100, 1)

    # Sizes. Reported in IAST bytes, which is what the tree publishes and what
    # the parent project compares across collections.
    iast = sorted(r["transliterated_bytes"] for r in sizes
                  if r.get("transliterated_bytes"))
    total_iast = sum(iast)
    stats["iast_mb"] = round(total_iast / 1024 / 1024, 1)
    stats["median_kb"] = round(iast[len(iast) // 2] / 1024, 1)
    # How few documents carry a sixth of the corpus -- the Puranas and
    # Monier-Williams against a median of a few KB.
    running, heaviest = 0, 0
    for size in reversed(iast):
        running += size
        heaviest += 1
        if running > total_iast / 6:
            break
    stats["heaviest"] = heaviest

    # Scanned sources, live only -- the same rule `build_tree` publishes under.
    #
    # Intersected with the stems `scans.jsonl` actually names, not just counted
    # off the liveness file. The two drift: `scan_liveness.jsonl` is written by
    # a separate networked stage and outlives a narrowing of the extraction
    # rule, so it currently holds 1012 stems against the 987 scans.jsonl
    # produces. Counting live rows alone publishes 895 where the tree says 873,
    # and a figure on this page disagreeing with the tree is exactly the drift
    # this module exists to prevent.
    live = {r["stem"] for r in liveness if r.get("status") == 200}
    kept = [s for s in scans if s["stem"] in live]
    if kept:
        stats["scans_live"] = len({s["stem"] for s in kept})
        stats["scan_links"] = len(kept)
        # `if s["doc_id"]` matches build_tree.summarize_scans: 32 links
        # carry no document at all, and counting the empty string as one
        # publishes 5,502 against the tree's 5,501.
        stats["scan_docs"] = len({s["doc_id"] for s in kept if s["doc_id"]})

    # The findings, so the prose can quote them without restating a number the
    # audit already computed.
    stats["missing"] = findings["missing"]["count"]
    stats["dead_scans"] = findings["dead_scans"]["count"]
    stats["dates_unusable"] = findings["dates"]["count"]
    # --- two dates, because there are two independent observations ----------
    #
    # The corpus and the scan-liveness check are measured on their own
    # schedules and go stale at their own rates -- 2.5 weeks apart when this
    # was written. One "last audited" date would average them into a claim
    # neither supports. Each is a `str` so `_fmt` passes it through: these are
    # dates, not quantities, and must not acquire thousands separators.
    #
    # `scans_checked` is an EXTERNAL_STAT: this audit does not measure scan
    # liveness, so a machine without that cache leaves the published date
    # exactly as it stands rather than blanking it.
    stats["corpus_date"] = corpus_date_str
    if findings["dead_scans"].get("checked_at"):
        stats["scans_checked"] = findings["dead_scans"]["checked_at"]
    stats.update(field_coverage(documents))

    # Why `subject` is not a browse axis: it is filled on 99.9% of documents
    # and is the same string on most of them, so it separates nothing. A float,
    # so `_fmt` gives it one decimal like every other percentage.
    subjects = collections.Counter(
        (d.get("subject") or "").strip() for d in documents)
    subjects.pop("", None)
    stats["subject_top_pct"] = round(
        subjects.most_common(1)[0][1] / total * 100, 1)

    stats.update(credit_stats(documents))

    # The site renders these with an older Sanscript build instead of
    # Aksharamukha. They are exactly the banner-less pages minus the two
    # metadata-only stubs, which is why `reconstruct_deva` has anything to do:
    # the missing title is a property of that template, not of those documents.
    stats["legacy_translit"] = sum(
        1 for d in documents if d.get("legacy_translit"))

    return stats


