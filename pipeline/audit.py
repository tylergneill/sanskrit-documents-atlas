def find_missing_documents(documents, catalogue, listings=()):
    """Documents the site's own indexes link but no longer serve.

    Our fetch got a 404 for each. These are the site disagreeing with itself,
    and among the few findings it could see without our help.

    **Both indexes carry every one.** The site publishes two independent ones --
    20 location pages (`/doc_shiva/`) and 87 listing pages
    (`/sanskrit/shiva/`) -- and all 25 dead links appear on both, which is
    consistent with the two agreeing exactly on all 9781 documents they name.
    So this is not one stale index shadowing a corrected one; the rot is shared.

    The listing pages naming each are attached, since those are the pages a
    maintainer would edit; the location is already in the doc_id.
    """
    held = {base_id(d["doc_id"]) for d in documents}
    missing = sorted({r["doc_id"] for r in catalogue} - held)
    on_listing = collections.defaultdict(list)
    for row in listings:
        for doc_id in row.get("doc_ids") or []:
            if doc_id not in held:
                on_listing[doc_id].append(row["slug"])
    return {
        "ids": missing,
        "count": len(missing),
        "by_location": collections.Counter(d.split("/")[0] for d in missing),
        "on_listing": {k: sorted(v) for k, v in on_listing.items()},
        # How many are named by a listing page as well as their location page.
        "on_both": sum(1 for d in missing if d in on_listing),
    }


def find_malformed_hrefs(catalogue):
    """Catalogue entries whose href is not a document path at all.

    Bad links on the site's own listing pages -- a literal space in one, a
    `.inf` target in the other. They inflate the site's own count by two, and
    the space nearly killed our fetch: `http.client.InvalidURL` is a
    `ValueError`, caught by neither the `HTTPError` nor the `URLError` handler.
    """
    bad = sorted(
        r["doc_id"] for r in catalogue
        if " " in r["doc_id"] or r["doc_id"].endswith(".inf")
    )
    return {"ids": bad, "count": len(bad)}


def find_missing_deva_titles(documents):
    """Documents carrying no Devanagari title, and those whose one is derived.

    `title_deva` is the ONLY one of a document's three names that can be
    transliterated. `title` is the site's free-text English label, and the
    `doc_id` stem only LOOKS like ITRANS -- real ITRANS reproduces it for 3.4%
    of documents, the site cannot write n~/N~ at all, and it spells the
    retroflex sibilant `shh` where ITRANS wants `Sh` (`vishhnu`, not `viShNu`).
    See notes/site-structure.md.
    Feeding `title` to a converter is a silent no-op -- no Devanagari code
    points, string returned unchanged, no error -- which was a real frontend
    bug until 2026-08-18. Without `title_deva` a document cannot render in the
    reader's chosen script at all.

    **The count is the SOURCE's gap, measured before our repair.** Since
    2026-08-28 a document whose page carries no Devanagari banner takes one
    rebuilt from its `itxtitle` (see parse_snapshot.reconstruct_deva), which
    fills `title_deva` -- so testing that field for emptiness measures what
    survives the fallback, not what sanskritdocuments.org is missing. It read 0
    from 2026-08-28 to 2026-09-07 for exactly that reason, reporting a clean
    source while 76 documents still had no title on the page. A document counts
    here if the site did not supply the title, whether or not we reconstructed
    one.

    `unrendered` is the residue that matters to a reader: no banner title AND
    no usable rebuild, so the document can only ever display as English.

    A reconstruction is not equivalent to a banner title. The site's
    romanization is not a real transliteration scheme, so the rebuild is an
    approximation -- lossy in the nasals it cannot express -- where a banner
    title is exact, and the `itxtitle` is sometimes a shorter variant of the
    banner title.
    """
    missing = [d for d in documents
               if d.get("title_deva_reconstructed")
               or not (d.get("title_deva") or "").strip()]
    ids = sorted(d["doc_id"] for d in missing)
    unrendered = sorted(d["doc_id"] for d in missing
                        if not (d.get("title_deva") or "").strip())
    return {"ids": ids, "count": len(ids),
            "unrendered": unrendered, "unrendered_count": len(unrendered)}


def find_unparseable_dates(documents, ceiling):
    """Documents whose `Latest update` will not parse.

    The field is hand-typed free text and the parser is deliberately forgiving
    (`Dec.`, `Julu`, `11-Feb-2015`, `January 5,2005` all resolve). What is left
    is either blank or corrupt -- `April 4, 20R2613`, `RFebruary 20, 2025`.

    This no longer means the document falls off the growth curve: attestation
    against the earlier corpora dates all of them (`bad_dates_rescued`). It is
    still a defect worth reporting -- the field is the corpus's own record of
    itself, and reconstructing it from a copy is not the same as it being
    right.

    Blank and corrupt are reported apart: one is an absence the site could
    fill, the other a typo it could fix, and they are different jobs.
    """
    blank, corrupt = [], []
    for doc in documents:
        raw = (doc.get("latest_update") or "").strip()
        if parse_update(raw, ceiling):
            continue
        (blank if not raw else corrupt).append((doc["doc_id"], raw))
    return {
        "blank": sorted(blank),
        "corrupt": sorted(corrupt),
        "count": len(blank) + len(corrupt),
    }


def find_incomplete_downloads(documents):
    """Documents not carrying the full set of seven format links.

    Nearly every document is published as its ITX source plus generated PDFs in
    Devanagari, Tamil, Telugu, Kannada and Gujarati. Where the set is short,
    the site is offering a format it does not have -- or, for the two carrying
    nothing at all, no download route whatsoever.
    """
    short = sorted(
        (d["doc_id"], len(d.get("downloads") or {}))
        for d in documents
        if len(d.get("downloads") or {}) < 7
    )
    return {"items": short, "count": len(short)}


def find_dead_scans(scans, liveness):
    """Scanned sources the site links that no longer resolve.

    Counted by STEM, not URL: page-anchored links (`/page/n170/mode/1up`)
    differ per document while naming one book, so counting URLs would report
    one dead volume many times over.

    Note what a scan link is and is not. The site never claims a scan is the
    exemplar its e-text was encoded from -- the same volume is cited by every
    text excerpted from it, and four consecutive entries on one listing page
    carry byte-identical sets of sixteen links. A scan is a printed witness of
    this text somewhere, and a dead one is a citation that has rotted.
    """
    if not liveness:
        return {"stems": [], "count": 0, "links": 0, "docs": 0,
                "by_kind": collections.Counter(), "unchecked": True,
                "checked_at": None}
    dead = {r["stem"]: r for r in liveness if r.get("status") != 200}
    stranded = [s for s in scans if s["stem"] in dead]
    return {
        "stems": sorted(dead),
        "count": len(dead),
        "links": len(stranded),
        "docs": len({s["doc_id"] for s in stranded if s["doc_id"]}),
        "by_kind": collections.Counter(r["kind"] for r in dead.values()),
        "detail": dead,
        "unchecked": False,
        # Not today: this is `check_scans`' observation, and it runs on its own
        # schedule. Dating it to the audit would claim a freshness the run has
        # not got -- the liveness cache was 2.5 weeks old when this was added.
        "checked_at": observed_on(liveness),
    }


def find_suppressed_listings(listings):
    """Listing pages this Atlas does not show, because the site duplicates them.

    Two kinds, both decided in `parse_listings.dedupe_aliases` and recorded on
    the surviving row rather than re-derived here -- the suppression and the
    finding must never be able to disagree:

    - a **byte-identical copy**: `/sanskrit/vishhnu/` returns the
      `/sanskrit/vishnu/` page, same bytes, two URLs.
    - a **strict subset**: `/sanskrit/giitaa/` lists 135 documents, all of them
      among `/sanskrit/gita/`'s 138 and in the same order.

    Rendering either put a row in the tree that told a reader nothing and
    double-counted its documents in the axis total. Suppressing them silently
    would be worse, though: an Atlas showing 85 pages where the site's sitemap
    says 87 owes the reader those two names.

    Kept slugs are the saner spelling where the site offers a choice -- `vishnu`
    over `vishhnu`, `gita` over `giitaa`, `shh`/`ii` being the site's own
    invention rather than any transliteration scheme.
    """
    items = []
    for row in listings:
        for alias in row.get("aliases") or []:
            items.append({
                "alias": alias,
                "kept": row["slug"],
                "note": (row.get("alias_notes") or {}).get(alias, "duplicate of"),
            })
    return {"items": sorted(items, key=lambda i: i["alias"]), "count": len(items)}


def find_unlisted_documents(documents, listings):
    """Documents that reach no listing page -- OUR bug, not the site's.

    Reads zero since 2026-08-25, and is kept as a standing guard because it
    caught a real 34-document hole once and would catch its return.

    That hole: two documents whose ids differ only by letter case
    (`gurvaShTakam` / `gurvashtakam` -- case is meaningful in ITRANS) collapse
    to one file on macOS and Windows, so `fetch_text` disambiguates the
    FILENAME with a `~<hash>` suffix. `parse_snapshot` then built `doc_id`
    from that filename, and since `site_listings.jsonl` records the id the SITE
    uses -- which has no suffix -- the join missed and all 34 fell off the
    topics axis.

    The fix was to strip the suffix where `doc_id` is minted, so a filesystem
    workaround never becomes a document's identity; `stem` still carries it,
    because that is what opens the file. Matching on a `base_id()` at each join
    was the alternative, and is worse -- it leaves the wrong id in the data and
    obliges every future consumer to remember the same unfolding.

    A nonzero count here means an id is reaching the tree in a spelling the
    site does not use.
    """
    listed = set()
    for row in listings:
        listed.update(row.get("doc_ids") or [])
    unlisted = sorted(d["doc_id"] for d in documents if d["doc_id"] not in listed)
    suffixed = [d for d in unlisted if CASE_SUFFIX_RE.search(d)]
    pairs = collections.defaultdict(list)
    for doc_id in suffixed:
        pairs[base_id(doc_id).lower()].append(doc_id)
    return {
        "ids": unlisted,
        "count": len(unlisted),
        "suffixed": len(suffixed),
        "pairs": dict(sorted(pairs.items())),
        "explained": len(suffixed) == len(unlisted),
    }


