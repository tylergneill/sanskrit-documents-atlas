"""Audit stage: what the source collection gets wrong, published for a reader.

Part of the point of an atlas is that an independent index is the only place a
source's own mistakes become visible. This finds them, describes them
specifically enough to act on, and regenerates a section of `docs/about.html`
between the AUDIT markers.

Modelled on `../e-bharatisampat-atlas/pipeline/audit.py`, which was in turn
modelled on the wikisource sibling -- the conventions are lifted deliberately so
the three projects stay legible to each other. None of their checks transfer;
those audit a database-backed catalogue and a MediaWiki, and this is a
hand-maintained static site.

## Standing rules

**It never mutates anything.** Not the source, not `data/`, not `tree.json`. An
audit finding is a thing for a human to look at, never an auto-correction. The
only file it writes is its own region of `about.html`.

**Every published number is re-derived by the run that publishes it.** The
failure this repo keeps hitting is a measured figure going stale in prose --
CLAUDE.md says it outright ("Don't cite a notes figure as fact -- re-derive
it"), and the About page had drifted to quoting `shivarahasya` at 728 when the
corpus said 784. An About page is the worst place for that because it looks
authoritative. Hence no baked-in constants to compare against.

## Entirely offline

Every check reads a file in `data/`, so the audit needs no network, no
credentials and no rivulet. It is free to run, and running it is the only way a
published figure gets re-derived.

## The checks

Five upstream defects, plus one of our own:

1. **Listed but not served** -- the catalogue links it, the site 404s it.
2. **Malformed catalogue hrefs** -- a space in a path, a `.inf` target.
3. **No Devanagari title** -- `title_deva` is the only transliterable name a
   document has (`title` is ad-hoc romanization, `doc_id` is ITRANS), so a
   document without one cannot be displayed in a reader's chosen script.
4. **Unparseable `Latest update`** -- free text, and some of it is corrupt
   (`April 4, 20R2613`). The corpus's only record of its own dates; an earlier
   copy can stand in for the growth curve, but not fix the field.
5. **Incomplete download sets** -- 9,753 of 9,756 carry all seven format links.
6. **Dead scanned-source links** -- checked by `make check-scans`.
7. **Documents the listing axis drops** -- OURS, not the site's. Reads zero
   since 2026-08-25; kept as a guard. See `find_unlisted_documents`.

Only the first five are rendered. Those are things sanskritdocuments.org could
fix; the seventh is a bug in this pipeline, and filing it under "problems that
should be fixed on sanskritdocuments.org" would blame the site for our own key
format. It is not published separately either -- the page is about the source
collection, so our own defects print to the console instead.

    make audit                # the checks, to the console
    make audit-update-about   # and rewrite the About region
"""

